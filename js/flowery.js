const textInterline = 2;
const charWidth = 8;
const charHeight = 16;

let boardSize;
let boardTop;
let boardLeft;

let vWidth = null;
let vHeight = null;

function drawText(num, time) {
    const textColor = "#fee502";
    let mystring = audios[num][0];
    if (mystring.lastIndexOf(" ") !== mystring.length - 1) {
        mystring += " ";
    }
    let y = boardTop - charHeight*2 - textInterline*2;
    let x = boardLeft + Math.floor((boardSize - (mystring.length * charWidth))/2);
    let mystringSliced = null;
    let prevChar = null;
    let prevString = null;
    let prevX = null;
    let xx = [];
    let mystrings = [];
    if (x < boardLeft) {
        let curChar = 0;
        while(mystring.indexOf(" ", curChar) !== -1) {
            prevChar = curChar;
            prevString = mystring.substring(0,prevChar);
            curChar = mystring.indexOf(" ", curChar)+1;
            mystringSliced = mystring.substring(0,curChar);
            prevX = x;
            x = boardLeft + Math.floor((boardSize-(mystringSliced.length*charWidth)) / 2);
            if (x < boardLeft) {
                xx.push(prevX + charWidth/2);
                mystrings.push(prevString);
                mystring = mystring.slice(prevChar);
            }
        }
        x = boardLeft + Math.floor((boardSize-(mystring.length*charWidth)) / 2);
    }
    xx.push(x);
    mystrings.push(mystring);
    let info = "";
    for (let j=0; j<xx.length; j++) {
        info += `<span id="msg${time}" style="position:absolute;color:${textColor};font-size:${charHeight}px;left:${xx[j]}px;top:${y}px;">${mystrings[j]}</span>`;
        y += textInterline + charHeight;
    }
    document.getElementById("message").innerHTML = info;
}

let playing = [];
let curIndex = playing.length;

function onlyUnique(value, index, array) {
    return array.indexOf(value) === index;
}

function playSound(num) {
    curIndex = playing.length;
    playing.push(num);
    let playIndex = curIndex;
    let tile = document.getElementById(`tile${num}`);
    let prevcol = num%2==0?"#fee502":"#fff06f";
    let backcol = "#716a3c";
    tile.style.backgroundColor = backcol;
    const audio = new Audio();
    audio.src = "snd/" + audios[num][1];
    audio.play();
    const time = (new Date()).getTime();
    drawText(num, time);
    audio.onpause = function() {
        playing[playIndex] = -1;
        if (playing.filter(onlyUnique).length === 1 && playing.includes(-1)) {
            playing = [];
        }
        if (!playing.includes(num)) {
            tile.style.backgroundColor = prevcol;
        }
        document.querySelectorAll(`#msg${time}`).forEach((e) => e.remove());
    }
}

function drawBoard() {
    if (window.visualViewport.width === vWidth && window.visualViewport.height === vHeight) {
        return null;
    }
    vWidth = window.visualViewport.width;
    vHeight = window.visualViewport.height;
    const maxWidth = vWidth - 4;
    const maxHeight = vHeight - charHeight*2 - textInterline*3 - 4;
    boardSize = Math.min(maxWidth, maxHeight);
    boardTop = Math.floor((vHeight - (boardSize - charHeight*2 - textInterline*3))/2);
    boardLeft = Math.floor((vWidth - boardSize)/2);
    const soundboard = document.getElementById("soundboard");
    const tileSize = boardSize/9;   // 9 tiles per row and column
    let tileTop = boardTop;
    let tileLeft = boardLeft;
    let html = "";
    for (let i = 0; i < audios.length; i++) {
        let backcol = i%2==0?"#fee502":"#fff06f";
        let textWidth = `${i+1}`.length * charWidth;
        let textTop = tileTop + Math.floor((tileSize - charHeight)/2);
        let textLeft = tileLeft + Math.floor((tileSize - textWidth)/2);
        let tile = `<div id="tile${i}" onclick="playSound(${i})" style="position:absolute;top:${tileTop}px;left:${tileLeft}px;width:${tileSize}px;height:${tileSize}px;background-color:${backcol};text-align:center;"></div><span onclick="playSound(${i})" style="position:absolute;user-select:none;top:${textTop}px;left:${textLeft}px;font-size:16px;color:black;">${i+1}</span>`;
        html += tile;
        tileLeft += tileSize;
        if ((i+1)%9===0) {
            tileTop += tileSize;
            tileLeft = boardLeft;
        }
    }
    soundboard.innerHTML = html;
}

document.addEventListener("DOMContentLoaded", drawBoard);
